$data = [System.IO.File]::ReadAllBytes($DatPath)
Write-Output "File: $DatPath"
Write-Output "Size: $($data.Length) bytes"
Write-Output ""

# Walk chunks
$offset = 0
$mmbList = @()
$typeCounts = @{}

while ($offset + 16 -lt $data.Length) {
    $info = [BitConverter]::ToUInt32($data, $offset + 4)
    $type = $info -band 0x7F
    $size = ($info -shr 3) -band 0x7FFFF0

    if ($size -eq 0 -or $offset + $size -gt $data.Length) { break }

    if (-not $typeCounts.ContainsKey($type)) { $typeCounts[$type] = 0 }
    $typeCounts[$type]++

    if ($type -eq 0x2E) {
        $mmbList += ,@($offset, $size)
    }

    $offset += $size
}

Write-Output "Chunk types: $(($typeCounts.Keys | Sort-Object | ForEach-Object { '0x{0:X2}={1}' -f $_, $typeCounts[$_] }) -join '  ')"
Write-Output "MMB chunks found: $($mmbList.Count)"
Write-Output ""
Write-Output "=== MMB header inspection (first $MaxMMBToDump) ==="
Write-Output ""

$stats = @{ D3_2 = 0; D3_other = 0; Decoded = 0; NotDecoded = 0; BadNumModel = 0 }
$d3Values = @{}
$n = 0

foreach ($entry in $mmbList) {
    $chunkStart = $entry[0]
    $chunkSize  = $entry[1]
    $dataOff    = $chunkStart + 16
    $dataLen    = $chunkSize - 16

    $declared = [FFXIDat]::DecodeMMB($data, $dataOff, $dataLen)

    # SMMBHEAD / SMMBHEAD2 occupy the first 16 bytes of chunk data
    $d1 = $data[$dataOff + 3]
    $d3 = $data[$dataOff + 4]
    $d4 = $data[$dataOff + 5]
    $d5 = $data[$dataOff + 6]
    $d6 = $data[$dataOff + 7]
    $magic = [FFXIDat]::Ascii($data, $dataOff, 3)

    if ($d1 -ge 5) { $stats.Decoded++ } else { $stats.NotDecoded++ }
    if ($d3 -eq 2) { $stats.D3_2++ } else { $stats.D3_other++ }
    if (-not $d3Values.ContainsKey($d3)) { $d3Values[$d3] = 0 }
    $d3Values[$d3]++

    # SMMBHeader starts at dataOff + 16
    $hdr = $dataOff + 16
    $imgID = [FFXIDat]::Ascii($data, $hdr, 16)
    $pieces = [BitConverter]::ToInt32($data, $hdr + 16)
    $offsetBlockHeader = [BitConverter]::ToUInt32($data, $hdr + 44)

    # First block header (if offsetBlockHeader is plausible)
    $numModel = "n/a"
    if ($offsetBlockHeader -gt 0 -and $offsetBlockHeader + 32 -lt $dataLen) {
        $numModel = [BitConverter]::ToInt32($data, $dataOff + $offsetBlockHeader)
        if ($numModel -lt 0 -or $numModel -gt 50) { $stats.BadNumModel++ }
    }

    if ($n -lt $MaxMMBToDump) {
        Write-Output ("[{0,3}] magic='{1}' declaredLen={2,-8} chunkLen={3,-8} D1={4,-3} D3={5,-3} D4={6,-3} D5={7,-3} D6={8,-3} pieces={9,-4} offBH={10,-8} numModel={11} imgID='{12}'" -f `
            $n, $magic, $declared, $dataLen, $d1, $d3, $d4, $d5, $d6, $pieces, $offsetBlockHeader, $numModel, $imgID)
    }
    $n++
}

Write-Output ""
Write-Output "=== Summary over all $($mmbList.Count) MMB chunks ==="
