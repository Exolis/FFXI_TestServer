    // Decode a single MMB payload in place. off = start of chunk data (chunkStart + 16).
    // limit = number of bytes available from off.
    public static int DecodeMMB(byte[] d, int off, int limit)
    {
        int declaredLen = d[off] | (d[off+1] << 8) | (d[off+2] << 16);
        int effLen = Math.Min(declaredLen, limit);

        if (d[off+3] >= 5)
        {
            uint key = KeyTable[d[off+5] ^ 0xF0];
            int keyCounter = 0;
            for (int pos = 8; pos < effLen; pos++)
            {
                uint x = ((key & 0xFF) << 8) | (key & 0xFF);
                key += (uint)(++keyCounter);
                d[off+pos] ^= (byte)(x >> (int)(key & 7));
                key += (uint)(++keyCounter);
            }
        }

        // second pass: block swap
        if (d[off+6] == 0xFF && d[off+7] == 0xFF)
        {
            uint key1 = (uint)(d[off+5] ^ 0xF0);
            uint key2 = KeyTable2[key1];
            int decodeCount = ((effLen - 8) & ~0xf) / 2;

            for (int pos = 0; pos + 8 <= decodeCount; pos += 8)
            {
                int a = off + 8 + pos;
                int b = off + 8 + decodeCount + pos;
                if (b + 8 > off + limit) break;
                if ((key2 & 1) != 0)
                {
                    for (int k = 0; k < 8; k++)
                    {
                        byte t = d[a+k]; d[a+k] = d[b+k]; d[b+k] = t;
                    }
                }
                key1 += 9;
                key2 += key1;
            }
        }
        return declaredLen;
    }

