$data = [System.IO.File]::ReadAllBytes($DatPath)

# Walk chunks, collect MMB and MZB
$offset = 0
$mmbChunks = @()
$mzbChunks = @()
while ($offset + 16 -lt $data.Length) {
    $info = [BitConverter]::ToUInt32($data, $offset + 4)
    $type = $info -band 0x7F
    $size = ($info -shr 3) -band 0x7FFFF0
    if ($size -eq 0 -or $offset + $size -gt $data.Length) { break }
    if ($type -eq 0x2E) { $mmbChunks += ,@($offset, $size) }
    if ($type -eq 0x1C) { $mzbChunks += ,@($offset, $size) }
    $offset += $size
}

# Decode MMBs, collect imgIDs
$mmbNames = New-Object System.Collections.Generic.HashSet[string]
$mmbOrdered = @()
foreach ($c in $mmbChunks) {
    $dataOff = $c[0] + 16
    $dataLen = $c[1] - 16
    [FFXIDat2]::DecodeMMB($data, $dataOff, $dataLen)
    $imgID = [FFXIDat2]::Str16($data, $dataOff + 16)
    [void]$mmbNames.Add($imgID)
    $mmbOrdered += $imgID
}

Write-Output "=== $($mmbOrdered.Count) MMB geometry blocks ($($mmbNames.Count) unique names) ==="
$mmbOrdered | Sort-Object | ForEach-Object { Write-Output "  $_" }

# Decode MZB and read placement ids
Write-Output ""
Write-Output "=== MZB placements ==="
foreach ($c in $mzbChunks) {
    $dataOff = $c[0] + 16
    $dataLen = $c[1] - 16
    $ok = [FFXIDat2]::DecodeMZB($data, $dataOff, $dataLen)
    if (-not $ok) { Write-Output "  MZB decode rejected (declared length > chunk)"; continue }

    $totalRecord100 = [BitConverter]::ToUInt32($data, $dataOff + 4) -band 0xFFFFFF
    $offsetEndRecord100 = [BitConverter]::ToUInt32($data, $dataOff + 20)
    $entryBytes = $offsetEndRecord100 - 32
    $entrySize = if ($totalRecord100 -gt 0) { [math]::Floor($entryBytes / $totalRecord100) } else { 0 }

    Write-Output "  totalRecord100=$totalRecord100  offsetEndRecord100=$offsetEndRecord100  => entrySize=$entrySize bytes"

    $matched = 0
    $unmatched = @{}
    for ($i = 0; $i -lt $totalRecord100; $i++) {
        $nodeBase = $dataOff + 32 + $i * $entrySize
        if ($nodeBase + 16 -gt $dataOff + $dataLen) { break }
        $id = [FFXIDat2]::Str16($data, $nodeBase)
        if ($mmbNames.Contains($id)) { $matched++ }
        else {
            if (-not $unmatched.ContainsKey($id)) { $unmatched[$id] = 0 }
            $unmatched[$id]++
        }
    }
    Write-Output "  matched to an MMB : $matched"
    Write-Output "  UNMATCHED         : $(($unmatched.Values | Measure-Object -Sum).Sum) placements across $($unmatched.Count) distinct ids"
    if ($unmatched.Count -gt 0) {
        Write-Output "  --- unmatched ids ---"
        $unmatched.GetEnumerator() | Sort-Object -Property @{Expression={$_.Value}; Descending=$true} | Select-Object -First 40 | ForEach-Object {
            Write-Output ("    '{0}' x{1}" -f $_.Key, $_.Value)
        }
    }
}

# Which MMBs are never referenced?
Write-Output ""
Write-Output "=== MMB blocks with no MZB placement (unreferenced geometry) ==="
$referenced = New-Object System.Collections.Generic.HashSet[string]
foreach ($c in $mzbChunks) {
    $dataOff = $c[0] + 16
    $dataLen = $c[1] - 16
    $totalRecord100 = [BitConverter]::ToUInt32($data, $dataOff + 4) -band 0xFFFFFF
    $offsetEndRecord100 = [BitConverter]::ToUInt32($data, $dataOff + 20)
    $entryBytes = $offsetEndRecord100 - 32
    $entrySize = if ($totalRecord100 -gt 0) { [math]::Floor($entryBytes / $totalRecord100) } else { 0 }
    for ($i = 0; $i -lt $totalRecord100; $i++) {
        $nodeBase = $dataOff + 32 + $i * $entrySize
        if ($nodeBase + 16 -gt $dataOff + $dataLen) { break }
        [void]$referenced.Add([FFXIDat2]::Str16($data, $nodeBase))
    }
}
$unref = $mmbNames | Where-Object { -not $referenced.Contains($_) }
Write-Output "  count: $(@($unref).Count)"
$unref | Sort-Object | ForEach-Object { Write-Output "    $_" }
